"""Upgrade and editorial contracts for the extended introductory A1 course."""
import hashlib
import json
from pathlib import Path
import tempfile
import threading
import unittest

from content_admin import ContentAdminService
from server import ROOT, answer_matches, create_server
from test_server import Client


class ExpandedCourseTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.course = json.loads((ROOT / 'data/curriculum.json').read_text())

    def test_previously_shipped_nine_lessons_keep_identical_meaning(self):
        # Captured from the released de97ac4 course, not regenerated by this test.
        original = json.dumps(self.course['lessons'][:9], ensure_ascii=False,
                              sort_keys=True, separators=(',', ':')).encode()
        self.assertEqual(hashlib.sha256(original).hexdigest(),
                         '8d84ac1d5894ea750fbae5a859d99b6d4e6098e1db2a6dcff749635812c66605')

    def test_new_lessons_pass_real_publication_schema_and_fit_answer_controls(self):
        service = ContentAdminService(None, ROOT, lambda: self.course)
        new = self.course['lessons'][9:]
        self.assertEqual(len(new), 18)
        for lesson in new:
            with self.subTest(lesson=lesson['id']):
                self.assertEqual(service.validate_lesson(lesson), lesson)
                for exercise in lesson['exercises']:
                    self.assertLessEqual(max(map(len, exercise['acceptedAnswers'])), 160)
                    if exercise['type'] == 'multiple-choice':
                        self.assertTrue(all(choice.isascii() for choice in exercise['choices']),
                                        'The answer controls request English, not Greek choices')
                    if exercise['type'] == 'reading':
                        self.assertIn(exercise['answer'].casefold(), exercise['passage'].casefold())

    def test_natural_punctuation_and_word_order_variants_are_accepted(self):
        by_id = {lesson['id']: lesson for lesson in self.course['lessons']}
        for lesson_id, exercise_id, response in [
            ('travel-tickets', 'ticket-to-athens', 'A ticket to Athens, please.'),
            ('happening-now', 'they-are-waiting', 'They are now waiting.'),
            ('happening-now', 'they-are-waiting', 'Now, they are waiting.'),
            ('daily-routine', 'get-up-seven', 'At seven, I get up.'),
            ('everyday-transport', 'town-by-bus', 'By bus, I go to town.'),
        ]:
            exercise = next(item for item in by_id[lesson_id]['exercises'] if item['id'] == exercise_id)
            with self.subTest(lesson=lesson_id, response=response):
                self.assertTrue(answer_matches(response, exercise))
                self.assertFalse(answer_matches('An unrelated incorrect answer', exercise))

    def test_upgrade_preserves_old_progress_and_unlocks_only_next_lesson(self):
        with tempfile.TemporaryDirectory() as directory:
            base = Path(directory)
            old_root = base / 'old-release'
            (old_root / 'data').mkdir(parents=True)
            (old_root / 'web').mkdir()
            old_course = {**self.course, 'lessons': self.course['lessons'][:9]}
            (old_root / 'data/curriculum.json').write_text(json.dumps(old_course))
            database = base / 'private/accounts.sqlite3'
            servers = []

            def start(root):
                server = create_server('127.0.0.1', 0, database, root)
                thread = threading.Thread(target=server.serve_forever, daemon=True)
                thread.start()
                servers.append((server, thread))
                return server

            def stop():
                server, thread = servers.pop()
                server.shutdown()
                server.server_close()
                thread.join()

            try:
                old_server = start(old_root)
                client = Client(old_server.server_port)
                self.assertEqual(client.register('upgrade@example.test')[0], 200)
                for lesson in old_course['lessons']:
                    status, _, _ = client.mutate('POST', '/api/progress', {
                        'lessonId': lesson['id'], 'answers': [item['answer'] for item in lesson['exercises']]})
                    self.assertEqual(status, 200)
                stop()

                current_server = start(ROOT)
                client.port = current_server.server_port
                status, session, _ = client.request('GET', '/api/session')
                self.assertEqual(status, 200)
                self.assertEqual(session['user']['email'], 'upgrade@example.test')
                self.assertEqual(session['progress']['xp'], 310)
                self.assertEqual(session['progress']['completedLessons'],
                                 [lesson['id'] for lesson in old_course['lessons']])
                self.assertEqual(client.request('GET', '/api/lesson-state?lessonId=family-members')[0], 200)
                self.assertEqual(client.request('GET', '/api/lesson-state?lessonId=possessive-words')[0], 409)
                lesson = self.course['lessons'][9]
                status, progress, _ = client.mutate('POST', '/api/progress', {
                    'lessonId': lesson['id'], 'answers': [item['answer'] for item in lesson['exercises']]})
                self.assertEqual(status, 200)
                self.assertEqual(progress['progress']['xp'], 350)
                self.assertEqual(client.request('GET', '/api/lesson-state?lessonId=possessive-words')[0], 200)
                self.assertEqual(len(client.request('GET', '/api/review')[1]['items']), 30)
            finally:
                while servers:
                    stop()


if __name__ == '__main__':
    unittest.main()
